// Pre-bakes the body/horn tint+multiply-shade composite (currently done at
// runtime in components/sheep-sprite.tsx via a tintColor layer + a
// mixBlendMode:"multiply" layer on top) into static PNGs, one per
// (art, color) combination. Colors are a small fixed set (the emotion
// palette), so this is a finite, one-time build step rather than something
// that needs to happen at runtime.
//
// Run with: node scripts/generate-tinted-character-assets.js
//
// Regenerate whenever the source body/horn art changes.

const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const ROOT = path.join(__dirname, "..");

// Every color bodyColor/hornColor can actually be in this app: the 6
// emotion colors (lib/emotion-colors.ts), the DEFAULT_BODY_COLOR fallback
// (components/sheep-sprite.tsx, used if an emotion string doesn't match),
// and NO_SUB_EMOTION_HORN_COLOR (lib/sheep-mapping.ts, used when a diary has
// no sub_emotion).
const COLORS = [
  { hex: "#8D5BDB", label: "不安・鬱" },
  { hex: "#FDB228", label: "楽しい・嬉しい" },
  { hex: "#FF4339", label: "怒り・イライラ" },
  { hex: "#008CDD", label: "悲しみ" },
  { hex: "#00B058", label: "安心・平常" },
  { hex: "#FF82AD", label: "好き・愛" },
  { hex: "#E5B450", label: "DEFAULT_BODY_COLOR" },
  { hex: "#F4F9F4", label: "NO_SUB_EMOTION_HORN_COLOR" },
];

const BODY_LEVELS = [1, 2, 3, 4, 5];
const BODY_SIZES = [1, 2, 3, 4, 5];
const HORN_VARIANTS = [1, 2, 3, 4, 5, 6, 7];

function slugForColor(hex) {
  return hex.replace("#", "").toLowerCase();
}

function hexToRgb(hex) {
  const m = hex.replace("#", "");
  return {
    r: parseInt(m.substring(0, 2), 16),
    g: parseInt(m.substring(2, 4), 16),
    b: parseInt(m.substring(4, 6), 16),
  };
}

// Replicates the runtime rendering: a flat `color` fill clipped to the
// source's alpha silhouette (RN's Image tintColor), with the original
// artwork's own shading multiplied on top (RN's mixBlendMode: "multiply").
async function generateTinted(srcPath, hex) {
  const { width, height } = await sharp(srcPath).metadata();
  const { r, g, b } = hexToRgb(hex);

  const tintLayer = await sharp({
    create: { width, height, channels: 4, background: { r, g, b, alpha: 1 } },
  })
    .composite([{ input: srcPath, blend: "dest-in" }])
    .png()
    .toBuffer();

  return sharp(tintLayer).composite([{ input: srcPath, blend: "multiply" }]).png().toBuffer();
}

async function generateSet(srcPath, outDir, outNameFor) {
  fs.mkdirSync(outDir, { recursive: true });
  let bytes = 0;
  for (const { hex } of COLORS) {
    const buffer = await generateTinted(srcPath, hex);
    const outPath = path.join(outDir, outNameFor(slugForColor(hex)));
    fs.writeFileSync(outPath, buffer);
    bytes += buffer.length;
    process.stdout.write(".");
  }
  return bytes;
}

// Emits components/tinted-character-sheets.ts: static require() lookups for
// every generated file. Metro (RN's bundler) needs require() paths to be
// literal strings it can see statically, so this can't be a runtime loop —
// it has to be codegen'd, same as the images themselves.
function buildManifest() {
  const lines = [];
  lines.push("// AUTO-GENERATED by scripts/generate-tinted-character-assets.js — do not edit by hand.");
  lines.push("// Keys are plain numbers (not BodyLevel/BodySize) to avoid a circular import");
  lines.push("// with sheep-sprite.tsx, which imports this file.");
  lines.push('import { ImageSourcePropType } from "react-native";');
  lines.push("");
  lines.push(
    "export const BODY_TINTED_SHEETS: Record<number, Record<number, Record<string, ImageSourcePropType>>> = {",
  );
  for (const level of BODY_LEVELS) {
    lines.push(`  ${level}: {`);
    for (const size of BODY_SIZES) {
      lines.push(`    ${size}: {`);
      for (const { hex } of COLORS) {
        const slug = slugForColor(hex);
        lines.push(`      "${slug}": require("../assets/character/body/lv${level}/tinted/lv${level}-sz${size}-${slug}.png"),`);
      }
      lines.push("    },");
    }
    lines.push("  },");
  }
  lines.push("};");
  lines.push("");
  lines.push("export const HORN_TINTED_SHEETS: Record<number, Record<string, ImageSourcePropType>> = {");
  for (const variant of HORN_VARIANTS) {
    const num = String(variant).padStart(3, "0");
    lines.push(`  ${variant}: {`);
    for (const { hex } of COLORS) {
      const slug = slugForColor(hex);
      lines.push(`    "${slug}": require("../assets/character/horn/tinted/horn-${num}-${slug}.png"),`);
    }
    lines.push("  },");
  }
  lines.push("};");
  lines.push("");

  const outPath = path.join(ROOT, "components/tinted-character-sheets.ts");
  fs.writeFileSync(outPath, lines.join("\n"));
  console.log(`wrote ${outPath}`);
}

async function main() {
  let totalBytes = 0;
  let totalFiles = 0;

  for (const level of BODY_LEVELS) {
    for (const size of BODY_SIZES) {
      const srcPath = path.join(ROOT, `assets/character/body/lv${level}/lv${level}-sz${size}.png`);
      const outDir = path.join(ROOT, `assets/character/body/lv${level}/tinted`);
      totalBytes += await generateSet(srcPath, outDir, (slug) => `lv${level}-sz${size}-${slug}.png`);
      totalFiles += COLORS.length;
    }
  }
  console.log(`\nbody: ${totalFiles} files`);

  const hornFilesBefore = totalFiles;
  for (const variant of HORN_VARIANTS) {
    const num = String(variant).padStart(3, "0");
    const srcPath = path.join(ROOT, `assets/character/horn/horn-${num}.png`);
    const outDir = path.join(ROOT, "assets/character/horn/tinted");
    totalBytes += await generateSet(srcPath, outDir, (slug) => `horn-${num}-${slug}.png`);
    totalFiles += COLORS.length;
  }
  console.log(`\nhorn: ${totalFiles - hornFilesBefore} files`);

  console.log(`\ntotal: ${totalFiles} files, ${(totalBytes / 1024 / 1024).toFixed(2)} MB`);

  buildManifest();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
